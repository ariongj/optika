import assert from 'node:assert/strict';
import { euro, roundMoney, cartLineLimit, cartAvailability, removeSubmittedLines, polarizedDiscountBase, trackingReference, trackingError, trackingStage, displayOrderDate } from '../src/checkoutExperience.js';
let checks = 0;
const equal = (actual, expected, message) => { assert.deepEqual(actual, expected, message); checks++; };
equal(euro(12.45).replace(/\s/g, ''), '12,45€', 'Cents are never hidden');
equal(roundMoney(125.55 * .15), 18.83, 'Percentage rounding matches server cents');
const products = [{ id: 'frame', stock: 3, polarized: true, price: 100, salePrice: 90 }];
const a = { lineId: 'a', signature: 'ready', productId: 'frame', quantity: 2 };
const b = { ...a, lineId: 'b', signature: 'lenses', quantity: 1 };
equal(cartLineLimit([a,b], a, products), 2, 'Other configurations consume same-product stock');
equal(cartAvailability([a,b], products), [], 'Exact stock is valid');
equal(cartAvailability([a,{...b,quantity:2}], products).length, 2, 'Oversubscribed product is flagged');
equal(cartLineLimit([a], a, []), 0, 'Removed product cannot be incremented');
equal(cartLineLimit([a], a, [{id:'frame',stock:0}]), 0, 'Zero stock must not fall back to 10');
equal(cartLineLimit([a], a, [{id:'frame',stock:99}]), 10, 'Per-line cap retained');
equal(removeSubmittedLines([a,b],[a]), [b], 'Clear only accepted lines');
equal(removeSubmittedLines([{...a,quantity:3},b],[a]), [{...a,quantity:1},b], 'Preserve quantities added after snapshot');
equal(removeSubmittedLines([{...a,signature:'changed'}],[a]), [{...a,signature:'changed'}], 'Preserve a newly edited configuration');
equal(polarizedDiscountBase([{...a,price:170,configuration:{sunTreatment:'No'}}], products), 180, 'Use catalogue flag and frame price, not lens surcharge or browser treatment');
equal(polarizedDiscountBase([a], [{...products[0],polarized:false}]), 0, 'Unflagged frame cannot receive polarized promotion');
equal(trackingReference('?order=om-test-123'), 'OM-TEST-123', 'Receipt deep link');
equal(trackingReference('?order=person%40example.test'), '', 'Only order reference can prefill');
equal(trackingStage({status:'Cancelled',fulfillmentStatus:'Delivered'}), -1, 'Cancelled never shows completed progress');
equal(trackingStage({status:'Returned'}), -1, 'Returned state is separate');
equal(trackingStage({status:'Return requested'}), -1, 'Return request is separate');
equal(trackingStage({status:'Pending'}), 0, 'New request');
equal(trackingStage({status:'In lab'}), 2, 'Lab');
equal(trackingStage({status:'Ready'}), 3, 'Ready');
equal(trackingStage({status:'Completed'}), 4, 'Completed');
equal(trackingStage({status:'Confirmed',fulfillmentStatus:'Shipped'}), 3, 'Delivery status participates');
equal(displayOrderDate('2026-10-02T12:00:00Z'), '2 tet 2026', 'Stable Albanian date');
equal(displayOrderDate('invalid'), 'Data nuk është e disponueshme', 'Invalid date safe');
equal(trackingError('order_not_found').includes('Nuk u gjet'), true, 'Unknown reference stays generic');
equal(trackingError('Failed to fetch').includes('shërbimin'), true, 'Network failure is not reported as missing order');
console.log(`PASS: ${checks} checkout and tracking checks.`);
