const values = new Map();
const storage = { getItem: (key) => values.get(key) ?? null, setItem: (key, value) => values.set(key, value), removeItem: (key) => values.delete(key) };
const filters = { ...catalogDefaults, color: 'Black gold', width: 'medium', search: 'Syze & lente', inStock: true };
const query = writeCatalogQuery('?utm_source=qa', filters, 'price-low');
assert.deepEqual(readCatalogQuery(query), { filters, sort: 'price-low' });
assert.ok(query.includes('utm_source=qa'));
assert.equal(writeCatalogQuery(query, catalogDefaults, 'featured'), 'utm_source=qa');
assert.equal(readCatalogQuery('?sort=invalid').sort, 'featured');
