const draft = { ...emptyCheckoutCustomer(), firstName: 'Synthetic', note: 'Never cache this', password: 'Never cache this', manualPrescription: 'Never cache this', shipping: 'pickup' };
saveCheckoutDraft(storage, 'a', draft);
assert.equal(readCheckoutDraft(storage, 'a').firstName, 'Synthetic');
assert.equal(readCheckoutDraft(storage, 'b').firstName, '');
assert.equal(readCheckoutDraft(storage, 'a').note, '');
assert.equal([...values.values()].some((value) => value.includes('Never cache this')), false);
clearCheckoutDraft(storage, 'a');
assert.equal(readCheckoutDraft(storage, 'a').firstName, '');
assert.deepEqual(readCheckoutDraft(null, 'a'), emptyCheckoutCustomer());
saveCheckoutDraft(null, 'a', draft);
const first = createCheckoutRequestIdentity(storage, 'a', webcrypto);
const body = { items: [{ productId: 'frame', quantity: 1 }], privateNote: 'Do not store me' };
const id = await first.get(body);
assert.equal(await first.get(body), id);
assert.equal(await createCheckoutRequestIdentity(storage, 'a', webcrypto).get(body), id, 'Reload keeps retry identity');
assert.notEqual(await createCheckoutRequestIdentity(storage, 'b', webcrypto).get(body), id, 'Account identities separated');
assert.notEqual(await first.get({ ...body, quantity: 2 }), id, 'Changed request gets a new identity');
assert.equal([...values.values()].some((value) => value.includes('Do not store me')), false);
first.clear();
assert.notEqual(await first.get(body), id);
