/**
 * Regenerates the Unicode tables at the end of server/api/lib/pricing.php (between `// <fold-tables>` and
 * `// </fold-tables>`), so the PHP port can fold text like the TS without the intl extension:
 *
 *   mvp_nfd_map()  char → c.normalize('NFD') without U+0300–036F   (foldCity() in src/lib/pricing.ts)
 *   mvp_nfkd_map() char → c.normalize('NFKD') without U+0300–036F  (fold() in src/lib/collections.ts)
 *
 *   node server/tests/pricing/gen-fold-tables.mjs
 *
 * Only characters the normalisation changes are listed, for the scripts a Kosovo/Balkan shop meets: Latin
 * (incl. Extended A/B/Additional/C/D), IPA and modifier letters, Greek, Cyrillic, general punctuation, super/sub-
 * scripts, letterlike symbols, number forms, enclosed alphanumerics, the ideographic space, Latin ligatures and
 * fullwidth ASCII. Anything outside these ranges passes through unchanged.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';

const TARGET = fileURLToPath(new URL('../../api/lib/pricing.php', import.meta.url));
const RANGES = [
  [0x00a0, 0x052f],
  [0x1d00, 0x1fff],
  [0x2000, 0x24ff],
  [0x2c60, 0x2c7f],
  [0x3000, 0x3000],
  [0xa720, 0xa7ff],
  [0xfb00, 0xfb06],
  [0xff01, 0xff5e],
];
const strip = (s) => s.replace(/[̀-ͯ]/g, '');

/** PHP string literal: single-quoted when plain ASCII, else double-quoted with \u{…} escapes. */
function php(s) {
  if (/^[\x20-\x7e]*$/.test(s)) return `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;
  let out = '"';
  for (const ch of s) {
    const cp = ch.codePointAt(0);
    if (cp >= 0x20 && cp < 0x7f) out += ch === '"' || ch === '\\' || ch === '$' ? `\\${ch}` : ch;
    else out += `\\u{${cp.toString(16).toUpperCase()}}`;
  }
  return `${out}"`;
}

function table(form) {
  const rows = [];
  for (const [a, b] of RANGES) {
    for (let cp = a; cp <= b; cp++) {
      const ch = String.fromCodePoint(cp);
      const to = strip(ch.normalize(form));
      if (to !== ch) rows.push(`${php(ch)}=>${php(to)}`);
    }
  }
  return rows;
}

function fn(name, form, what) {
  const rows = table(form);
  const lines = [];
  for (let i = 0; i < rows.length; i += 8) lines.push(`        ${rows.slice(i, i + 8).join(', ')},`);
  return [
    `/** ${what} — ${rows.length} entries, generated by server/tests/pricing/gen-fold-tables.mjs (Node ${process.versions.node}, Unicode ${process.versions.unicode}). */`,
    `function ${name}(): array`,
    '{',
    '    static $m = null;',
    '    return $m ??= [',
    ...lines,
    '    ];',
    '}',
  ].join('\n');
}

const block = [
  '// <fold-tables>',
  fn('mvp_nfd_map', 'NFD', "c → c.normalize('NFD') without U+0300–036F"),
  '',
  fn('mvp_nfkd_map', 'NFKD', "c → c.normalize('NFKD') without U+0300–036F"),
  '// </fold-tables>',
].join('\n');

const src = readFileSync(TARGET, 'utf8');
const re = /\/\/ <fold-tables>[\s\S]*?\/\/ <\/fold-tables>/;
if (!re.test(src)) throw new Error(`markers not found in ${TARGET}`);
writeFileSync(TARGET, src.replace(re, () => block));
console.log(`fold tables written to ${TARGET}`);
