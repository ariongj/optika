export type ShopT = (key: keyof (typeof T)['me'] & string, vars?: Record<string, string | number>) => string;

/** "1 proizvod / 2 proizvoda / 21 proizvod" — Serbian singular for …1 (except …11). */
export function countLabel(t: ShopT, lang: Lang, n: number) {
  const one = lang === 'me' ? n % 10 === 1 && n % 100 !== 11 : n === 1;
  return t(one ? 'countOne' : 'countMany', { n });
}
